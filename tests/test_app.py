def test_signup_duplicate_returns_400(client):
    # Arrange
    activity_name = "Chess Club"
    email = activities[activity_name]["participants"][0]
    initial_count = len(activities[activity_name]["participants"])

    # Act
    response = client.post(f"/activities/{activity_name}/signup", params={"email": email})

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "student already signed up"
    assert len(activities[activity_name]["participants"]) == initial_count


def test_unregister_from_activity_success(client):
    # Arrange
    activity_name = "Chess Club"
    email = activities[activity_name]["participants"][0]
    initial_count = len(activities[activity_name]["participants"])

    # Act
    response = client.delete(f"/activities/{activity_name}/unregister", params={"email": email})

    # Assert
    assert response.status_code == 200
    assert email in response.json()["message"]
    assert activity_name in response.json()["message"]
    updated = client.get("/activities").json()
    assert email not in updated[activity_name]["participants"]
    assert len(updated[activity_name]["participants"]) == initial_count - 1


